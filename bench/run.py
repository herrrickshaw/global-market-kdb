#!/usr/bin/env python3
"""Run the q / DuckDB / Polars benchmark and write bench/RESULTS.md.

Five operations the signal study performs, on the full Parquet warehouse:
load all US daily bars (2016-2026), median dollar volume by symbol and year,
per-symbol rolling windows, per-date cross-sectional rank, and an as-of join of
India daily bars to annual fundamentals. Each engine runs in its own process,
reports the median of --reps runs, and a check value (row count or checksum)
that must agree across engines, so every engine is timed on the same answer.

Run:  python bench/run.py [--reps 5]
"""
from __future__ import annotations

import argparse
import json
import platform
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OPS = ["load_us", "groupby_median", "window_by_sym", "rank_by_date", "asof_join_in"]
LABEL = {"load_us": "load US Parquet (16.7M rows)", "groupby_median": "median $vol by sym, year",
         "window_by_sym": "5d return + 63-row mean |r| by sym", "rank_by_date": "rank 5d return by date",
         "asof_join_in": "as-of join IN bars to fundamentals"}
QVAR = {"load_us": "load_us_peach", "groupby_median": "groupby_median_peach",
        "rank_by_date": "rank_by_date_sorted"}


def lines(cmd):
    p = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
    if p.returncode:
        sys.exit(f"{cmd[0]} failed:\n{p.stderr}{p.stdout}")
    return [json.loads(x) for x in p.stdout.splitlines() if x.startswith("{")]


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--reps", type=int, default=5)
    ap.add_argument("--root", default=str(Path.home() / ".cache/market-warehouse"))
    ap.add_argument("--q", default=str(Path.home() / ".kx/bin/q"))
    a = ap.parse_args()
    py = sys.executable
    rows = lines([a.q, "bench/bench.q", "-root", a.root, "-reps", str(a.reps), "-s", "4", "-q"])
    for eng in ("duckdb", "polars"):
        for th in (1, 4):
            rows += lines([py, "bench/bench_py.py", eng, "--root", a.root, "--reps", str(a.reps),
                           "--threads", str(th)])
    res = {(r["engine"], r["op"]): r for r in rows}
    import duckdb, polars
    qv = subprocess.run([a.q, "-q"], input='-1 string[.z.K]," ",string .z.k; exit 0\n',
                        capture_output=True, text=True).stdout.strip()
    engines = ["q", "q (peach / sorted)", "duckdb-1t", "duckdb-4t", "polars-1t", "polars-4t"]
    out = ["# Benchmark: q vs DuckDB vs Polars on the study's own operations", "",
           f"Machine: {platform.machine()} {platform.mac_ver()[0] or platform.platform()}, "
           f"{subprocess.run(['sysctl', '-n', 'machdep.cpu.brand_string'], capture_output=True, text=True).stdout.strip()}, "
           f"{subprocess.run(['sysctl', '-n', 'hw.ncpu'], capture_output=True, text=True).stdout.strip()} cores, "
           f"{int(subprocess.run(['sysctl', '-n', 'hw.memsize'], capture_output=True, text=True).stdout) // 2**30} GB. "
           f"KDB-X {qv} (Community, `-s 4`), DuckDB {duckdb.__version__}, Polars {polars.__version__}.", "",
           f"Median (min) wall time in ms over {a.reps} runs, data in memory except for the load row. "
           "Generated by `bench/run.py`.", "",
           "The machine has 8 GB and was swapping during these runs (other applications open), so "
           "timings are noisy: q's rolling-window step measured anywhere from 1.0 s to 9.6 s across "
           "separate runs. Read the minimum as the better estimate of each engine's speed, and "
           "differences under about 2x as noise.", "",
           "| operation | " + " | ".join(engines) + " | check agrees |",
           "|---|" + "---|" * (len(engines) + 1)]
    for op in OPS:
        cells, checks = [], []
        for e in engines:
            key = ("q", QVAR.get(op, op)) if e.startswith("q (") else (e, op)
            r = res.get(key)
            if e.startswith("q (") and op not in QVAR:
                cells.append("–")
                continue
            cells.append(f"{r['ms']:,.0f} ({r['min_ms']:,.0f})" if r else "n/a")
            if r:
                checks.append(float(r["check"]))
        agree = max(checks) - min(checks) <= 1e-6 * max(abs(c) for c in checks) + 1e-9
        out.append(f"| {LABEL[op]} | " + " | ".join(cells) + f" | {'yes' if agree else 'NO'} |")
    out += ["", "Notes:",
            "- `q` is a direct translation of each operation. `q (peach / sorted)` is the idiomatic version: "
            "`peach` over year files or years (KDB-X Community allows 4 secondary threads), and per-date "
            "ranking on rows stored by date, as they are in a date-partitioned HDB.",
            "- q-sql on an in-memory table runs single-threaded unless the work is split with `peach`; "
            "DuckDB and Polars parallelise internally, so they are shown at 1 and 4 threads.",
            "- The rank row uses ordinal ranks in all engines (q `rank`, DuckDB `row_number`, Polars "
            "`rank(\"ordinal\")`); ties and nulls may be ordered differently, so only the row count is checked.",
            "- This measures one laptop and one dataset. It is not a STAC-M3 style benchmark and makes no "
            "claim beyond these numbers."]
    (ROOT / "bench" / "RESULTS.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
